func calcTotalSize(files []PackageFile) int64 {
	var total int64
	for _, f := range files {
		if len(f.Content) > 0 {
			total += int64(len(f.Content))
		} else if f.SourcePath != "" {
			if fi, err := os.Stat(f.SourcePath); err == nil {
				total += fi.Size()
			}
		}
	}
	return total
}

func createIPK(outputPath string, controlFiles, dataFiles []PackageFile) error {
	dataTarGz, err := makeTarGz(dataFiles)
	if err != nil {
		return fmt.Errorf("make data.tar.gz: %w", err)
	}

	controlTarGz, err := makeTarGz(controlFiles)
	if err != nil {
		return fmt.Errorf("make control.tar.gz: %w", err)
	}

	outerFiles := []PackageFile{
		{TargetRelPath: "debian-binary", Content: []byte("2.0\n"), Mode: 0644},
		{TargetRelPath: "control.tar.gz", Content: controlTarGz, Mode: 0644},
		{TargetRelPath: "data.tar.gz", Content: dataTarGz, Mode: 0644},
	}

	return writeTarGzFile(outputPath, outerFiles)
}

func makeTarGz(files []PackageFile) ([]byte, error) {
	var buf bytes.Buffer
	gw := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gw)

	for _, f := range files {
		var content []byte
		var size int64
		if len(f.Content) > 0 {
			content = f.Content
			size = int64(len(content))
		} else if f.SourcePath != "" {
			data, err := os.ReadFile(f.SourcePath)
			if err != nil {
				return nil, fmt.Errorf("read file %s: %w", f.SourcePath, err)
			}
			content = data
			size = int64(len(content))
		}

		hdr := &tar.Header{
			Name:     filepath.ToSlash(f.TargetRelPath),
			Mode:     f.Mode,
			Size:     size,
			Uid:      0,
			Gid:      0,
			Uname:    "root",
			Gname:    "root",
			ModTime:  time.Unix(1762426800, 0),
			Typeflag: tar.TypeReg,
			Format:   tar.FormatPAX,
		}

		if err := tw.WriteHeader(hdr); err != nil {
			return nil, fmt.Errorf("tar write header %s: %w", f.TargetRelPath, err)
		}
		if _, err := tw.Write(content); err != nil {
			return nil, fmt.Errorf("tar write content %s: %w", f.TargetRelPath, err)
		}
	}

	if err := tw.Close(); err != nil {
		return nil, err
	}
	if err := gw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func writeTarGzFile(outputPath string, files []PackageFile) error {
	outFile, err := os.Create(outputPath)
	if err != nil {
		return err
	}
	defer outFile.Close()

	gw := gzip.NewWriter(outFile)
	defer gw.Close()

	tw := tar.NewWriter(gw)
	defer tw.Close()

	for _, f := range files {
		var content []byte
		var size int64
		if len(f.Content) > 0 {
			content = f.Content
			size = int64(len(content))
		} else if f.SourcePath != "" {
			data, err := os.ReadFile(f.SourcePath)
			if err != nil {
				return fmt.Errorf("read file %s: %w", f.SourcePath, err)
			}
			content = data
			size = int64(len(content))
		}

		hdr := &tar.Header{
			Name:     filepath.ToSlash(f.TargetRelPath),
			Mode:     f.Mode,
			Size:     size,
			Uid:      0,
			Gid:      0,
			Uname:    "root",
			Gname:    "root",
			ModTime:  time.Unix(1762426800, 0),
			Typeflag: tar.TypeReg,
			Format:   tar.FormatPAX,
		}

		if err := tw.WriteHeader(hdr); err != nil {
			return fmt.Errorf("tar write header %s: %w", f.TargetRelPath, err)
		}
		if _, err := tw.Write(content); err != nil {
			return fmt.Errorf("tar write content %s: %w", f.TargetRelPath, err)
		}
	}

	return nil
}
